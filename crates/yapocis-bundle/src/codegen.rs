//! Generate one typed Rust struct per bundled interface variant from a bundle's
//! `manifest.json`, for a crate's `build.rs` to write into `$OUT_DIR` and
//! `include!`. The `yapocis` crate uses it for Yapocis3's bundle, and a crate that
//! vendors another project's bundle (its kernels found through `YAPOCIS_PROJECT`,
//! exported with `yapocis-tools bundle --project-only`) uses it the same way with
//! [`Options::yapocis_path`] set to `"yapocis"`.
//!
//! The generated code expects the including crate to define
//! `pub static MANIFEST: LazyLock<Manifest>` for its bundle, which each struct's
//! `Interface::manifest()` returns.

use serde::Deserialize;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// How the generated code refers to the `yapocis` crate.
#[derive(Debug, Clone)]
pub struct Options {
    /// `"crate"` inside the `yapocis` crate itself, `"yapocis"` from another crate.
    pub yapocis_path: String,
}

impl Default for Options {
    fn default() -> Self {
        Options {
            yapocis_path: "yapocis".to_string(),
        }
    }
}

/// The generator's output.
#[derive(Debug)]
pub struct Generated {
    /// Rust source to write to `$OUT_DIR` and `include!`.
    pub code: String,
    /// Files the build script should re-run on (the manifest and every source).
    pub rerun_if_changed: Vec<PathBuf>,
    /// The manifest's `yapocis_version`.
    pub yapocis_version: String,
}

#[derive(Deserialize)]
struct Manifest {
    schema_version: u32,
    yapocis_version: String,
    interfaces: Vec<Iface>,
}

#[derive(Deserialize)]
struct Iface {
    name: String,
    variant: String,
    id: String,
    kernels: Vec<Kernel>,
    sources: BTreeMap<String, Source>,
}

#[derive(Deserialize)]
struct Source {
    path: String,
}

#[derive(Deserialize)]
struct Kernel {
    name: String,
    params: Vec<Param>,
    user_args: Vec<String>,
}

#[derive(Deserialize)]
struct Param {
    name: String,
    kind: String,
    dtype: String,
    #[serde(default)]
    role: Option<String>,
}

const SCHEMA_VERSION: u32 = 1;

fn rust_type(dtype: &str) -> &'static str {
    match dtype {
        "float32" => "f32",
        "float64" => "f64",
        "float16" => "::half::f16",
        "int8" => "i8",
        "int16" => "i16",
        "int32" => "i32",
        "int64" => "i64",
        "uint8" => "u8",
        "uint16" => "u16",
        "uint32" => "u32",
        "uint64" => "u64",
        "complex64" => "::num_complex::Complex<f32>",
        "complex128" => "::num_complex::Complex<f64>",
        "bool" => "u8",
        other => panic!("unsupported dtype {other}"),
    }
}

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
];

fn ident(s: &str) -> String {
    let mut out: String = s
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if out
        .chars()
        .next()
        .map(|c| c.is_ascii_digit())
        .unwrap_or(true)
    {
        out.insert(0, '_');
    }
    if KEYWORDS.contains(&out.as_str()) {
        out.push('_');
    }
    out
}

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = true;
    for c in s.chars() {
        if c.is_ascii_alphanumeric() {
            if up {
                out.extend(c.to_uppercase());
                up = false;
            } else {
                out.push(c);
            }
        } else {
            up = true;
        }
    }
    out
}

/// Generate the typed API for the bundle at `bundle_dir` from its manifest text.
pub fn generate(
    manifest_text: &str,
    bundle_dir: &Path,
    opts: &Options,
) -> Result<Generated, String> {
    let manifest: Manifest =
        serde_json::from_str(manifest_text).map_err(|e| format!("parse manifest: {e}"))?;
    if manifest.schema_version != SCHEMA_VERSION {
        return Err(format!(
            "bundle schema {} but this generator understands {}",
            manifest.schema_version, SCHEMA_VERSION
        ));
    }
    let y = &opts.yapocis_path;
    let mut code = String::new();
    writeln!(
        code,
        "// Generated by yapocis_bundle::codegen from {}/manifest.json (yapocis {}). Do not edit.",
        bundle_dir.display(),
        manifest.yapocis_version
    )
    .unwrap();
    writeln!(code, "use {y}::host::{{self, Interface}};").unwrap();
    writeln!(code, "use {y}::rt::{{Buffer, CallArg, CallOptions, CallOutput, Device, HostView, HostViewMut, Program}};").unwrap();
    writeln!(code, "use {y}::{{Manifest, Result}};").unwrap();
    writeln!(code, "use ndarray::{{ArrayD, ArrayViewD, ArrayViewMutD}};").unwrap();
    writeln!(code).unwrap();

    let mut rerun = vec![bundle_dir.join("manifest.json")];
    for iface in &manifest.interfaces {
        for src in iface.sources.values() {
            rerun.push(bundle_dir.join(&src.path));
        }
        gen_interface(&mut code, iface, bundle_dir);
    }
    Ok(Generated {
        code,
        rerun_if_changed: rerun,
        yapocis_version: manifest.yapocis_version,
    })
}

fn gen_interface(code: &mut String, iface: &Iface, bundle: &Path) {
    let module = ident(&iface.id.replace('.', "_"));
    let struct_name = camel(&iface.id);
    let doc_variant = if iface.variant == "default" {
        String::new()
    } else {
        format!(" (variant `{}`)", iface.variant)
    };
    writeln!(
        code,
        "/// Interface `{}`{doc_variant}: {} kernels.",
        iface.name,
        iface.kernels.len()
    )
    .unwrap();
    writeln!(code, "pub mod {module} {{").unwrap();
    writeln!(code, "    use super::*;").unwrap();
    writeln!(code, "    pub const ID: &str = {:?};", iface.id).unwrap();
    writeln!(code, "    /// Rendered kernel sources, by backend name.").unwrap();
    writeln!(
        code,
        "    pub fn source(backend: &str) -> Option<&'static str> {{"
    )
    .unwrap();
    writeln!(code, "        match backend {{").unwrap();
    for (backend, src) in &iface.sources {
        let path = bundle.join(&src.path);
        writeln!(
            code,
            "            {backend:?} => Some(include_str!({:?})),",
            path.display().to_string()
        )
        .unwrap();
    }
    writeln!(code, "            _ => None,").unwrap();
    writeln!(code, "        }}").unwrap();
    writeln!(code, "    }}").unwrap();
    writeln!(code).unwrap();
    writeln!(
        code,
        "    /// `{}`{doc_variant} compiled for one device.",
        iface.name
    )
    .unwrap();
    writeln!(code, "    pub struct {struct_name} {{").unwrap();
    writeln!(code, "        program: Program,").unwrap();
    writeln!(code, "    }}").unwrap();
    writeln!(code).unwrap();
    writeln!(code, "    impl Interface for {struct_name} {{").unwrap();
    writeln!(code, "        const ID: &'static str = ID;").unwrap();
    writeln!(
        code,
        "        fn from_program(program: Program) -> Self {{ {struct_name} {{ program }} }}"
    )
    .unwrap();
    writeln!(
        code,
        "        fn program(&self) -> &Program {{ &self.program }}"
    )
    .unwrap();
    writeln!(
        code,
        "        fn source(backend: &str) -> Option<&'static str> {{ source(backend) }}"
    )
    .unwrap();
    writeln!(
        code,
        "        fn manifest() -> &'static Manifest {{ &crate::MANIFEST }}"
    )
    .unwrap();
    writeln!(code, "    }}").unwrap();
    writeln!(code).unwrap();
    writeln!(code, "    impl {struct_name} {{").unwrap();
    writeln!(code, "        /// Compile this interface for `device`.").unwrap();
    writeln!(
        code,
        "        pub fn load(device: &Device) -> Result<Self> {{ host::load::<Self>(device) }}"
    )
    .unwrap();
    writeln!(
        code,
        "        pub fn program(&self) -> &Program {{ &self.program }}\n        pub fn into_program(self) -> Program {{ self.program }}"
    )
    .unwrap();
    writeln!(
        code,
        "        pub fn device(&self) -> &Device {{ self.program.device() }}"
    )
    .unwrap();
    for kernel in &iface.kernels {
        gen_kernel(code, kernel);
    }
    writeln!(code, "    }}").unwrap();
    writeln!(code, "}}").unwrap();
    writeln!(code).unwrap();
}

struct ArgSpec {
    ident: String,
    kind: ArgKind,
    ty: &'static str,
}

enum ArgKind {
    In,
    InOut,
    Resident,
    Scalar,
}

fn gen_kernel(code: &mut String, kernel: &Kernel) {
    // Signature from user args; output types from out_like params.
    let mut args: Vec<ArgSpec> = Vec::new();
    for name in &kernel.user_args {
        let p = kernel
            .params
            .iter()
            .find(|p| &p.name == name && !matches!(p.kind.as_str(), "dim" | "out_like"))
            .unwrap();
        let kind = match (p.kind.as_str(), p.role.as_deref()) {
            ("scalar", _) => ArgKind::Scalar,
            ("buffer", Some("in")) => ArgKind::In,
            ("buffer", Some("inout")) | ("buffer", Some("out")) => ArgKind::InOut,
            ("buffer", Some("resident")) => ArgKind::Resident,
            other => panic!("unexpected param {other:?}"),
        };
        args.push(ArgSpec {
            ident: ident(name),
            kind,
            ty: rust_type(&p.dtype),
        });
    }
    let outs: Vec<&'static str> = kernel
        .params
        .iter()
        .filter(|p| p.kind == "out_like")
        .map(|p| rust_type(&p.dtype))
        .collect();

    let method = ident(&kernel.name);
    let mut sig = String::new();
    for a in &args {
        let ty = match a.kind {
            ArgKind::In => format!("&ArrayViewD<'_, {}>", a.ty),
            ArgKind::InOut => format!("&mut ArrayViewMutD<'_, {}>", a.ty),
            ArgKind::Resident => format!("&Buffer<{}>", a.ty),
            ArgKind::Scalar => a.ty.to_string(),
        };
        write!(sig, ", {}: {}", a.ident, ty).unwrap();
    }
    let ret = match outs.len() {
        0 => "()".to_string(),
        1 => format!("ArrayD<{}>", outs[0]),
        _ => format!(
            "({})",
            outs.iter()
                .map(|t| format!("ArrayD<{t}>"))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    };

    // Shared body: build CallArgs
    let mut body = String::new();
    for a in &args {
        match a.kind {
            ArgKind::In => {
                writeln!(
                    body,
                    "            let {0}_std = host::standard({0});",
                    a.ident
                )
                .unwrap();
            }
            ArgKind::InOut => {
                writeln!(
                    body,
                    "            let {0}_shape = {0}.shape().to_vec();",
                    a.ident
                )
                .unwrap();
                writeln!(
                    body,
                    "            let {0}_slice = host::slice_mut({0})?;",
                    a.ident
                )
                .unwrap();
            }
            _ => {}
        }
    }
    writeln!(body, "            let mut args = [").unwrap();
    for a in &args {
        let expr = match a.kind {
            ArgKind::In => format!(
                "CallArg::In(HostView::of({0}_std.as_slice().unwrap(), {0}.shape()))",
                a.ident
            ),
            ArgKind::InOut => format!(
                "CallArg::InOut(HostViewMut::of({0}_slice, &{0}_shape))",
                a.ident
            ),
            ArgKind::Resident => format!("CallArg::Buffer({}.as_any())", a.ident),
            ArgKind::Scalar => format!("CallArg::Scalar({} as f64)", a.ident),
        };
        writeln!(body, "                {expr},").unwrap();
    }
    writeln!(body, "            ];").unwrap();
    writeln!(
        body,
        "            Ok(self.program.call({:?}, &mut args, opts)?)",
        kernel.name
    )
    .unwrap();

    // _with variant: dynamic output
    writeln!(code).unwrap();
    writeln!(code, "        /// Kernel `{}` with explicit [`CallOptions`] (sizes, async); outputs are returned untyped.", kernel.name).unwrap();
    writeln!(
        code,
        "        pub fn {method}_with(&self, opts: &CallOptions{sig}) -> Result<CallOutput> {{"
    )
    .unwrap();
    code.push_str(&body);
    writeln!(code, "        }}").unwrap();

    // typed variant
    writeln!(code).unwrap();
    writeln!(code, "        /// Kernel `{}`.", kernel.name).unwrap();
    writeln!(
        code,
        "        pub fn {method}(&self{sig}) -> Result<{ret}> {{"
    )
    .unwrap();
    let call_args: Vec<String> = args.iter().map(|a| a.ident.clone()).collect();
    writeln!(
        code,
        "            let out = self.{method}_with(&CallOptions::default(){}{})?;",
        if call_args.is_empty() { "" } else { ", " },
        call_args.join(", ")
    )
    .unwrap();
    match outs.len() {
        0 => writeln!(code, "            let _ = out; Ok(())").unwrap(),
        1 => writeln!(code, "            host::one_output::<{}>(out)", outs[0]).unwrap(),
        n => {
            writeln!(
                code,
                "            let mut it = host::out_like_outputs(out).into_iter();"
            )
            .unwrap();
            let mut parts = Vec::new();
            for (i, t) in outs.iter().enumerate() {
                writeln!(code, "            let o{i} = host::to_array::<{t}>(it.next().expect(\"output {i}\"))?;").unwrap();
                parts.push(format!("o{i}"));
            }
            let _ = n;
            writeln!(code, "            Ok(({}))", parts.join(", ")).unwrap();
        }
    }
    writeln!(code, "        }}").unwrap();
}
